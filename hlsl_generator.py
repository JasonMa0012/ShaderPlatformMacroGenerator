from excel_reader import ExcelConfig, FeatureRow, GroupHeader


def _calc_keyword_width(features: list) -> int:
    max_len = 0
    for f in features:
        if isinstance(f, FeatureRow):
            max_len = max(max_len, len(f.keyword))
    return max_len


def generate_hlsl(config: ExcelConfig) -> str:
    lines = []
    keyword_width = _calc_keyword_width(config.features)

    if config.prefix_lines:
        for line in config.prefix_lines:
            lines.append(line)
        lines.append("")

    lines.append("// Generated by Shader Platform Macro Generator (https://github.com/JasonMa0012/ShaderPlatformMacroGenerator)")
    lines.append("// Unity Builtin Macros: https://docs.unity3d.com/2022.3/Documentation/Manual/SL-BuiltinMacros.html")
    lines.append("// Unreal Builtin Macros: https://github.com/EpicGames/UnrealEngine/blob/5.5/Engine/Shaders/Public/Platform.ush")
    lines.append("")

    macro = config.file_include_macro
    lines.append(f"#ifndef {macro}")
    lines.append(f"    #define {macro}")
    lines.append("")

    for i, platform in enumerate(config.platforms):
        directive = "#if" if i == 0 else "#elif"
        lines.append(f"    // {platform.name}")
        lines.append(f"    {directive} {platform.condition}")

        for j, quality in enumerate(config.qualities):
            q_directive = "#if" if j == 0 else "#elif"
            lines.append(f"        {q_directive} {quality.condition}")

            for feature in config.features:
                if isinstance(feature, GroupHeader):
                    lines.append(f"            // {feature.name}")
                elif isinstance(feature, FeatureRow):
                    value = feature.values.get((platform.name, quality.name), "")
                    padded_keyword = feature.keyword.ljust(keyword_width)
                    lines.append(f"            #define {padded_keyword} {value}")

        lines.append("        #endif")

    lines.append("    #endif")
    lines.append("")
    lines.append(f"#endif // {macro}")
    lines.append("")

    return "\n".join(lines)
